CREATE WAREHOUSE IF NOT EXISTS INSURANCE_FRAUD_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS INSURANCE_FRAUD_DW;

CREATE SCHEMA IF NOT EXISTS
    INSURANCE_FRAUD_DW.CLAIMS_ANALYTICS;


USE WAREHOUSE INSURANCE_FRAUD_WH;

USE DATABASE INSURANCE_FRAUD_DW;

USE SCHEMA CLAIMS_ANALYTICS;

CREATE TABLE IF NOT EXISTS CLAIMS (
    ID NUMBER(38, 0) NOT NULL,
    CLAIM_NUMBER VARCHAR(100) NOT NULL,
    CUSTOMER_ID NUMBER(38, 0) NOT NULL,
    POLICY_ID NUMBER(38, 0) NOT NULL,
    VEHICLE_ID NUMBER(38, 0) NOT NULL,
    SUBMITTED_BY_USER_ID NUMBER(38, 0) NOT NULL,
    INCIDENT_DATE DATE NOT NULL,
    INCIDENT_LOCATION VARCHAR(500),
    INCIDENT_DESCRIPTION VARCHAR,
    CLAIMED_AMOUNT NUMBER(18, 2),
    RISK_SCORE NUMBER(10, 0),
    RISK_BAND VARCHAR(30),
    STATUS VARCHAR(100),
    CREATED_AT TIMESTAMP_TZ,
    UPDATED_AT TIMESTAMP_TZ,
    REPORTED_REGISTRATION_NUMBER VARCHAR(100),
    REPORTED_VIN VARCHAR(100),
    CALCULATED_RISK_BAND VARCHAR(30),
    CLAIM_AMOUNT_CATEGORY VARCHAR(30),
    ETL_LOADED_AT TIMESTAMP_TZ
);

