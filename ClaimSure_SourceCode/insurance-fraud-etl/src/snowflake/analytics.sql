CREATE OR REPLACE VIEW CUSTOMER_CLAIM_HISTORY AS

SELECT
    CUSTOMER_ID,

    COUNT(*) AS TOTAL_CLAIMS,

    SUM(CLAIMED_AMOUNT) AS TOTAL_CLAIMED_AMOUNT,

    AVG(CLAIMED_AMOUNT) AS AVERAGE_CLAIM_AMOUNT,

    ROUND(AVG(RISK_SCORE), 2) AS AVERAGE_RISK_SCORE,

    COUNT_IF(
        CALCULATED_RISK_BAND = 'LOW'
    ) AS LOW_RISK_CLAIMS,

    COUNT_IF(
        CALCULATED_RISK_BAND = 'MEDIUM'
    ) AS MEDIUM_RISK_CLAIMS,

    COUNT_IF(
        CALCULATED_RISK_BAND = 'HIGH'
    ) AS HIGH_RISK_CLAIMS,

    COUNT_IF(
        STATUS = 'REJECTED'
    ) AS REJECTED_CLAIMS,

    COUNT_IF(
        STATUS = 'CLEARED_FOR_PROCESSING'
    ) AS CLEARED_CLAIMS,

    MIN(INCIDENT_DATE) AS FIRST_INCIDENT_DATE,

    MAX(INCIDENT_DATE) AS LATEST_INCIDENT_DATE

FROM CLAIMS

GROUP BY CUSTOMER_ID;


CREATE OR REPLACE TABLE FRAUD_RULE_ANALYSIS AS

SELECT
    R.ID AS RULE_CONFIGURATION_ID,

    R.RULE_CODE,

    R.RULE_NAME,

    R.DESCRIPTION,

    R.WEIGHT,

    R.ENABLED,

    COUNT(F.ID) AS TOTAL_FLAGS,

    COUNT(DISTINCT F.CLAIM_ID) AS DISTINCT_FLAGGED_CLAIMS,

    COALESCE(
        SUM(F.SCORE_CONTRIBUTION),
        0
    ) AS TOTAL_SCORE_CONTRIBUTION,

    ROUND(
        AVG(F.SCORE_CONTRIBUTION),
        2
    ) AS AVERAGE_SCORE_CONTRIBUTION,

    MAX(F.CREATED_AT) AS LAST_FLAG_CREATED_AT

FROM FRAUD_RULE_CONFIGURATIONS R

LEFT JOIN CLAIM_FLAGS F
    ON F.RULE_CONFIGURATION_ID = R.ID

GROUP BY
    R.ID,
    R.RULE_CODE,
    R.RULE_NAME,
    R.DESCRIPTION,
    R.WEIGHT,
    R.ENABLED;



CREATE OR REPLACE TABLE INVESTIGATION_PERFORMANCE AS

WITH NOTE_COUNTS AS (

    SELECT
        INVESTIGATION_ID,

        COUNT(*) AS TOTAL_NOTES

    FROM INVESTIGATION_NOTES

    GROUP BY INVESTIGATION_ID

),

REQUEST_COUNTS AS (

    SELECT
        INVESTIGATION_ID,

        COUNT(*) AS TOTAL_EVIDENCE_REQUESTS,

        COUNT_IF(
            STATUS = 'FULFILLED'
        ) AS FULFILLED_EVIDENCE_REQUESTS

    FROM EVIDENCE_REQUESTS

    GROUP BY INVESTIGATION_ID

),

DECISION_COUNTS AS (

    SELECT
        INVESTIGATION_ID,

        COUNT(*) AS TOTAL_DECISIONS

    FROM CLAIM_DECISIONS

    GROUP BY INVESTIGATION_ID

)

SELECT
    I.ID AS INVESTIGATION_ID,

    I.CLAIM_ID,

    C.CLAIM_NUMBER,

    I.INVESTIGATOR_USER_ID,

    I.STATUS AS INVESTIGATION_STATUS,

    I.STARTED_AT,

    I.COMPLETED_AT,

    CASE
        WHEN I.COMPLETED_AT IS NOT NULL
        THEN DATEDIFF(
            'HOUR',
            I.STARTED_AT,
            I.COMPLETED_AT
        )
        ELSE NULL
    END AS RESOLUTION_HOURS,

    COALESCE(
        N.TOTAL_NOTES,
        0
    ) AS TOTAL_NOTES,

    COALESCE(
        R.TOTAL_EVIDENCE_REQUESTS,
        0
    ) AS TOTAL_EVIDENCE_REQUESTS,

    COALESCE(
        R.FULFILLED_EVIDENCE_REQUESTS,
        0
    ) AS FULFILLED_EVIDENCE_REQUESTS,

    COALESCE(
        D.TOTAL_DECISIONS,
        0
    ) AS TOTAL_DECISIONS

FROM INVESTIGATIONS I

LEFT JOIN CLAIMS C
    ON C.ID = I.CLAIM_ID

LEFT JOIN NOTE_COUNTS N
    ON N.INVESTIGATION_ID = I.ID

LEFT JOIN REQUEST_COUNTS R
    ON R.INVESTIGATION_ID = I.ID

LEFT JOIN DECISION_COUNTS D
    ON D.INVESTIGATION_ID = I.ID;


CREATE OR REPLACE VIEW ENTITY_MATCH_ANALYSIS AS

SELECT
    MATCH_TYPE,

    REVIEW_STATUS,

    COUNT(*) AS TOTAL_MATCHES,

    COUNT(DISTINCT CLAIM_ID) AS DISTINCT_CURRENT_CLAIMS,

    COUNT(DISTINCT MATCHED_CLAIM_ID) AS DISTINCT_MATCHED_CLAIMS,

    ROUND(
        AVG(CONFIDENCE_SCORE),
        4
    ) AS AVERAGE_CONFIDENCE_SCORE,

    MAX(CREATED_AT) AS LAST_MATCH_CREATED_AT

FROM ENTITY_MATCHES

GROUP BY
    MATCH_TYPE,
    REVIEW_STATUS;

CREATE OR REPLACE VIEW EVIDENCE_STORAGE_ANALYSIS AS

SELECT
    EVIDENCE_TYPE,

    STORAGE_PROVIDER,

    COUNT(*) AS TOTAL_EVIDENCE_RECORDS,

    COUNT_IF(
        FILE_NAME IS NOT NULL
    ) AS RECORDS_WITH_FILES,

    COUNT_IF(
        FILE_NAME IS NULL
    ) AS METADATA_ONLY_RECORDS,

    SUM(
        COALESCE(FILE_SIZE, 0)
    ) AS TOTAL_FILE_SIZE_BYTES

FROM EVIDENCE

GROUP BY
    EVIDENCE_TYPE,
    STORAGE_PROVIDER;

CREATE OR REPLACE VIEW CLAIM_DECISION_ANALYSIS AS

SELECT
    DECISION,

    COUNT(*) AS TOTAL_DECISIONS,

    COUNT(DISTINCT CLAIM_ID) AS DISTINCT_CLAIMS,

    MIN(DECIDED_AT) AS FIRST_DECISION_AT,

    MAX(DECIDED_AT) AS LATEST_DECISION_AT

FROM CLAIM_DECISIONS

GROUP BY DECISION;

