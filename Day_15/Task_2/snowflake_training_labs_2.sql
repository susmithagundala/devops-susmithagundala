SELECT
    CURRENT_USER() AS USER_NAME,
    CURRENT_ROLE() AS ACTIVE_ROLE,
    CURRENT_WAREHOUSE() AS ACTIVE_WAREHOUSE,
    CURRENT_DATABASE() AS ACTIVE_DATABASE,
    CURRENT_SCHEMA() AS ACTIVE_SCHEMA;
CREATE DATABASE IF NOT EXISTS COMPANYS_DATA;
SHOW DATABASES LIKE 'COMPANYS_DATA';
SHOW DATABASES;
CREATE SCHEMA IF NOT EXISTS COMPANYS_DATA.HR_RECORDS;
USE SCHEMA COMPANYS_DATA.HR_RECORDS;
SHOW SCHEMAS IN DATABASE COMPANYS_DATA;
CREATE WAREHOUSE IF NOT EXISTS STAFF_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;
USE WAREHOUSE STAFF_WH;
SHOW WAREHOUSES LIKE 'STAFF_WH';
SELECT CURRENT_WAREHOUSE();
CREATE TABLE IF NOT EXISTS COMPANYS_DATA.HR_RECORDS.EMPLOYEE_DETAILS
(
    EMPLOYEE_ID NUMBER(10,0),
    EMPLOYEE_NAME VARCHAR(100),
    DEPARTMENT VARCHAR(50),
    SALARY NUMBER(12,2),
    LOCATION VARCHAR(100)
);
SHOW TABLES LIKE 'EMPLOYEE_DETAILS'
IN SCHEMA COMPANYS_DATA.HR_RECORDS;
DESCRIBE TABLE COMPANYS_DATA.HR_RECORDS.EMPLOYEE_DETAILS;
CREATE FILE FORMAT IF NOT EXISTS
COMPANYS_DATA.HR_RECORDS.STAFF_CSV_FORMAT
TYPE = CSV
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE;
SHOW FILE FORMATS IN SCHEMA COMPANYS_DATA.HR_RECORDS;
DESCRIBE FILE FORMAT COMPANYS_DATA.HR_RECORDS.STAFF_CSV_FORMAT;
CREATE STAGE IF NOT EXISTS
COMPANYS_DATA.HR_RECORDS.STAFF_STAGE
FILE_FORMAT = COMPANYS_DATA.HR_RECORDS.STAFF_CSV_FORMAT;
SHOW STAGES IN SCHEMA COMPANYS_DATA.HR_RECORDS;
LIST @COMPANYS_DATA.HR_RECORDS.STAFF_STAGE;
LIST @COMPANYS_DATA.HR_RECORDS.STAFF_STAGE;
COPY INTO COMPANYS_DATA.HR_RECORDS.EMPLOYEE_DETAILS
FROM @COMPANYS_DATA.HR_RECORDS.STAFF_STAGE
FILE_FORMAT = (
    FORMAT_NAME =
    'COMPANYS_DATA.HR_RECORDS.STAFF_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';
SELECT * FROM COMPANYS_DATA.HR_RECORDS.EMPLOYEE_DETAILS;
SELECT COUNT(*) AS TOTAL_EMPLOYEES
FROM COMPANYS_DATA.HR_RECORDS.EMPLOYEE_DETAILS;
SELECT *
FROM COMPANYS_DATA.HR_RECORDS.EMPLOYEE_DETAILS
LIMIT 5;

